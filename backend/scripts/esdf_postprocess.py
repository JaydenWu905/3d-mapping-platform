#!/usr/bin/env python3
"""把 Voxblox 导出的 ASCII PLY 转成 XY/XZ/YZ 三张切片 PNG，并生成浏览器用的 3D 点云预览。

PLY 字段格式（由 voxel_points_to_esdf.cpp 导出）：
  x y z distance red green blue

产物：
  slice_{xy,xz,yz}.png   三视图切片（固定 ±1.5 m 红蓝图例，白色=无有效采样）
  esdf_vis_web.ply       二进制降采样点云，供前端 3D 查看器使用
  slices_meta.json       切片坐标/距离/分辨率元信息 + 3D 预览点云元信息
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image

# 与切片 PNG 完全一致的固定图例（米）；正侧为原 TSDF 传感器侧。
LEGEND_D_MIN = -1.5
LEGEND_D_MAX = 1.5

# 每个查看平面：(u 轴, v 轴, 法向轴)。与 render_slice 的 (u_all, v_all, w_all) 一致。
PLANE_AXES = {
    "xy": ("x", "y", "z"),
    "xz": ("x", "z", "y"),
    "yz": ("y", "z", "x"),
}


def load_ply_data(path: Path) -> np.ndarray:
    """读取 ASCII PLY（只处理我们自己导出的格式）。"""
    with path.open("r", encoding="utf-8") as fh:
        while True:
            line = fh.readline()
            if not line:
                raise ValueError("PLY 文件头不完整")
            if line.strip() == "end_header":
                break
        # 读取所有数据行（忽略末尾空行）
        data = np.loadtxt(fh, dtype=np.float64, ndmin=2)
    if data.shape[0] == 0 or data.shape[1] != 7 or not np.isfinite(data).all():
        raise ValueError("Empty, invalid or nonfinite ESDF preview")
    return data


def render_slice(
    u: np.ndarray, v: np.ndarray, d: np.ndarray,
    out_png: Path, res: int, d_min: float, d_max: float
) -> dict | None:
    """把 (u,v) 散点投影到 res×res 网格，颜色按 distance 映射：红近蓝远。"""
    u_min, u_max = float(u.min()), float(u.max())
    v_min, v_max = float(v.min()), float(v.max())
    span = max(u_max - u_min, v_max - v_min)
    if span < 1e-6:
        return None

    # 归一化到 0..res-1
    px = ((u - u_min) / span * (res - 1)).astype(int)
    py = ((v - v_min) / span * (res - 1)).astype(int)
    px = np.clip(px, 0, res - 1)
    py = np.clip(py, 0, res - 1)

    # 距离 → 颜色
    norm = np.clip((d - d_min) / max(d_max - d_min, 1e-6), 0, 1)
    r = (255 * (1.0 - norm)).astype(np.uint8)
    b = (255 * norm).astype(np.uint8)
    g = np.zeros_like(r)

    # 全白背景，逐点覆盖
    img = np.full((res, res, 3), 255, dtype=np.uint8)
    img[py, px] = np.stack([r, g, b], axis=-1)

    # 图像 y 轴翻转（工程习惯：y 朝上）
    img = np.flipud(img)
    Image.fromarray(img).save(out_png)

    return {
        "file": out_png.name,
        "u_range": [u_min, u_max],
        "v_range": [v_min, v_max],
        "distance_range": [float(d_min), float(d_max)],
        "distance_range_observed": [float(d.min()), float(d.max())],
        "image_size_px": [int(res), int(res)],
        "pixel_size_m": float(span / max(res - 1, 1)),
        # 行 0 对应 v_max（渲染前 flipud），便于前端在图上标注方向。
        "image_orientation": "row0=v_max",
    }


def write_web_preview(
    data: np.ndarray, out_ply: Path, max_points: int, seed: int = 0
) -> dict:
    """写一份二进制 PLY 点云预览：x y z distance + 距离着色 rgb。

    真实 ESDF 预览动辄上千万点（实测 1770 万点 / 541 MB ASCII），浏览器无法直接加载，
    因此这里按均匀随机抽样降到 max_points 量级；原始 ASCII PLY 保留给下载与专业软件。
    """
    source_points = int(data.shape[0])
    if source_points > max_points > 0:
        keep = np.random.default_rng(seed).random(source_points) < (max_points / source_points)
        sample = data[keep]
    else:
        sample = data
    count = int(sample.shape[0])

    xyz = np.ascontiguousarray(sample[:, 0:3], dtype="<f4")
    dist = np.ascontiguousarray(sample[:, 3], dtype="<f4")
    norm = np.clip((sample[:, 3] - LEGEND_D_MIN) / (LEGEND_D_MAX - LEGEND_D_MIN), 0.0, 1.0)
    red = (255.0 * (1.0 - norm)).astype(np.uint8)
    blue = (255.0 * norm).astype(np.uint8)
    green = np.zeros(count, dtype=np.uint8)

    record = np.empty(count, dtype=[
        ("x", "<f4"), ("y", "<f4"), ("z", "<f4"), ("distance", "<f4"),
        ("red", "u1"), ("green", "u1"), ("blue", "u1"),
    ])
    record["x"], record["y"], record["z"] = xyz[:, 0], xyz[:, 1], xyz[:, 2]
    record["distance"] = dist
    record["red"], record["green"], record["blue"] = red, green, blue

    header = "\n".join([
        "ply",
        "format binary_little_endian 1.0",
        "comment esdf_web_preview generated by esdf_postprocess.py",
        f"comment source_points {source_points}",
        f"comment downsample_max_points {max_points}",
        f"element vertex {count}",
        "property float x",
        "property float y",
        "property float z",
        "property float distance",
        "property uchar red",
        "property uchar green",
        "property uchar blue",
        "end_header",
        "",
    ])
    with out_ply.open("wb") as fh:
        fh.write(header.encode("ascii"))
        fh.write(record.tobytes())

    return {
        "file": out_ply.name,
        "format": "ply/binary_little_endian",
        "properties": ["x", "y", "z", "distance", "red", "green", "blue"],
        "point_count": count,
        "source_point_count": source_points,
        "downsample_ratio": round(count / source_points, 6) if source_points else 0.0,
        "max_points": int(max_points),
        "distance_range": [LEGEND_D_MIN, LEGEND_D_MAX],
        "distance_range_observed": [float(dist.min()), float(dist.max())] if count else [0.0, 0.0],
        "size_bytes": int(out_ply.stat().st_size),
        "unit": "meter",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input_ply", required=True, type=Path)
    parser.add_argument("--output_dir", required=True, type=Path)
    parser.add_argument("--resolution", type=int, default=480)
    parser.add_argument("--web_max_points", type=int, default=400_000,
                        help="3D 浏览器预览点云的最大点数（0 表示不降采样）")
    parser.add_argument("--skip_web_preview", action="store_true")
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    import os
    reporter = None
    if os.environ.get("PLATFORM_ALGORITHM_PROGRESS_PATH"):
        from app.models.live_progress import ProgressReporter
        reporter = ProgressReporter()
        reporter.emit("loading_preview",force=True)
    print(f"[postprocess] 读取 {args.input_ply}")
    data = load_ply_data(args.input_ply)
    print(f"[postprocess] 共 {data.shape[0]} 点, {data.shape[1]} 列")

    if data.shape[1] < 7:
        raise ValueError(f"PLY 至少 7 列 (x y z distance r g b)，实际 {data.shape[1]}")

    xs, ys, zs, dist = data[:, 0], data[:, 1], data[:, 2], data[:, 3]
    d_min, d_max = LEGEND_D_MIN, LEGEND_D_MAX  # Fixed signed meter legend; matches declared preview window.
    print(f"[postprocess] distance 范围: [{d_min:.3f}, {d_max:.3f}]")

    bounds = {
        axis: [float(values.min()), float(values.max())]
        for axis, values in (("x", xs), ("y", ys), ("z", zs))
    }

    planes = {
        "xy": (xs, ys, zs),
        "xz": (xs, zs, ys),
        "yz": (ys, zs, xs),
    }

    planes_meta: dict[str, dict] = {}
    if reporter: reporter.emit("slice_rendering",0,len(planes),scope="step",unit="切片方向",force=True)
    for index, (name, (u_all, v_all, w_all)) in enumerate(planes.items()):
        w_center = float(np.median(w_all))
        thickness = 0.1  # 切片厚度
        mask = np.abs(w_all - w_center) < thickness
        if mask.sum() < 50:
            print(f"[postprocess] {name} 切片点数太少，跳过")
            if reporter: reporter.emit("slice_rendering",index+1,len(planes),scope="step",unit="切片方向",force=True)
            continue
        print(f"[postprocess] {name} 切片 {mask.sum()} 点")
        out_png = args.output_dir / f"slice_{name}.png"
        order = np.argsort(-np.abs(w_all[mask] - w_center), kind="stable")
        info = render_slice(
            u_all[mask][order], v_all[mask][order], dist[mask][order],
            out_png, args.resolution, d_min, d_max
        )
        if info:
            u_axis, v_axis, normal_axis = PLANE_AXES[name]
            info.update(
                u_axis=u_axis,
                v_axis=v_axis,
                normal_axis=normal_axis,
                center_m=w_center,
                half_thickness_m=thickness,
                thickness_m=2.0 * thickness,
                sampled_points=int(mask.sum()),
                unit="meter",
                unknown_color="white",
                preview_abs_distance_max_m=LEGEND_D_MAX,
            )
            planes_meta[name] = info
        if reporter: reporter.emit("slice_rendering",index+1,len(planes),scope="step",unit="切片方向",force=True)

    meta: dict = {
        "schema_version": "1.0",
        "unit": "meter",
        "image_resolution_px": int(args.resolution),
        "distance_legend_range_m": [d_min, d_max],
        "preview_abs_distance_max_m": LEGEND_D_MAX,
        "bounds_m": bounds,
        "planes": planes_meta,
    }

    if not args.skip_web_preview:
        web_ply = args.output_dir / "esdf_vis_web.ply"
        try:
            web = write_web_preview(data, web_ply, args.web_max_points)
        except Exception as exc:  # 3D 预览失败不应拖垮切片与原生产物
            print(f"[postprocess] 3D 预览点云生成失败，跳过：{exc}")
            web = None
        if web is not None:
            web["bounds_m"] = bounds
            meta["web_preview"] = web
            print(f"[postprocess] 3D 预览点云 {web['point_count']} 点 "
                  f"({web['size_bytes'] / 1024 / 1024:.2f} MB)，源 {web['source_point_count']} 点")

    (args.output_dir / "slices_meta.json").write_text(
        json.dumps(meta, indent=2), encoding="utf-8"
    )
    print(f"[postprocess] 完成，生成 {len(planes_meta)} 张切片")


if __name__ == "__main__":
    main()
